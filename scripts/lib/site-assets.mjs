import { readFileSync } from "node:fs"
import { createHash } from "node:crypto"
import subsetFont from "subset-font"
import { sitePath } from "../../lib/site/config.mjs"

export const packageHeaders = (headers) => headers.split("\n").map((line) => line.startsWith("/") ? sitePath(line) : line).join("\n")

// The default pair is on every page, preloaded, before anything else can paint, so each of its faces is cut in two
// by unicode-range: the core every page reads (ASCII and the site's own punctuation) and the rest of the face's
// range, which a browser fetches only for a page that sets one of those letters. The other pairs load when chosen.
export const CORE_RANGE = "U+0020-007E,U+00A0,U+00B0,U+00B7,U+00D7,U+2013-2014,U+2018-2019,U+201C-201D,U+2022,U+2026,U+202F,U+2190-2193,U+2212"

const points = (range) => new Set(range.split(",").flatMap((part) => {
  const [a, b = a] = part.trim().replace(/^U\+/i, "").split("-")
  const lo = parseInt(a, 16), hi = parseInt(b, 16)
  return Array.from({ length: hi - lo + 1 }, (_, i) => lo + i)
}))
const hex = (n) => n.toString(16).toUpperCase().padStart(4, "0")
function ranges(set) {
  const s = [...set].sort((a, b) => a - b), out = []
  for (let i = 0; i < s.length; ) {
    let j = i
    while (j + 1 < s.length && s[j + 1] === s[j] + 1) j++
    out.push(i === j ? `U+${hex(s[i])}` : `U+${hex(s[i])}-${hex(s[j])}`)
    i = j + 1
  }
  return out.join(",")
}

/** Docs fonts use files; installed registry fonts keep their portable data URLs. Returns the core files to preload. */
export async function siteFonts() {
  const files = new Map()
  const faces = []
  const preload = []
  const core = points(CORE_RANGE)
  for (const pair of ["fonts", "fonts-press", "fonts-paris", "fonts-salon"]) {
    const source = readFileSync(`registry/0nlytype/styles/${pair}.css`, "utf8")
    for (const [face] of source.matchAll(/@font-face \{[^}]+\}/g)) {
      const family = face.match(/font-family: "([^"]+)"/)[1].toLowerCase().replaceAll(" ", "-")
      const style = face.match(/font-style: ([^;]+)/)[1]
      const data = face.match(/url\(data:font\/woff2;base64,([^)]+)\)/)[1]
      const bytes = Buffer.from(data, "base64")
      const add = async (part, range) => {
        const out = range ? await subsetFont(bytes, String.fromCodePoint(...[...points(range)].filter((p) => p >= 0x20)), { targetFormat: "woff2" }) : bytes
        const name = `${family}-${style}-${createHash("sha256").update(out).digest("hex").slice(0, 10)}.woff2`
        files.set(name, out)
        let next = part.replace(/url\(data:font\/woff2;base64,[^)]+\)/, `url("${sitePath(`/fonts/${name}`)}")`)
          .replace("font-display: swap", `font-display: ${pair === "fonts" ? "optional" : "swap"}`)
        if (range) next = next.replace(/unicode-range: [^;]+;/, `unicode-range: ${range};`)
        faces.push(next)
        return name
      }
      if (pair !== "fonts") { await add(face); continue }
      const all = points(face.match(/unicode-range: ([^;]+);/)[1])
      // The core face comes first, so anything reading the first face of a family (scripts/build-og.mjs) gets it.
      preload.push(await add(face, ranges([...all].filter((p) => core.has(p)))))
      await add(face, ranges([...all].filter((p) => !core.has(p))))
    }
  }
  return { css: "/* Generated by scripts/build-registry.mjs from the portable registry fonts. */\n\n" + faces.join("\n\n") + "\n", files, preload }
}
